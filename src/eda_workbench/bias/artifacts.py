"""Load a self-contained evaluation bundle.

Never use the profiled dataset as the eval table or as a source of
predictions. The model is loaded only when a distinct ``eval_path`` exists.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any

import joblib
import pandas as pd

from eda_workbench.bias.prepare import configured_path


@dataclass
class EvalBundle:
    """Optional eval artifacts. Missing pieces become skip reasons, not fallbacks."""

    predictions: pd.DataFrame | None = None
    eval_features: pd.DataFrame | None = None
    model: Any = None
    metrics_skip: str | None = None
    shap_skip: str | None = None


def _same_file(path_a: str | Path, path_b: str | Path) -> bool:
    try:
        return (
            Path(path_a).expanduser().resolve() == Path(path_b).expanduser().resolve()
        )
    except OSError:
        return False


def _read_csv(path: str, dataset_config: dict) -> pd.DataFrame:
    return pd.read_csv(
        path,
        sep=dataset_config.get("separator", ","),
        encoding=dataset_config.get("encoding", "utf-8"),
    )


def _refuse_if_profiled(path: str, profiled_path: str | None, kind: str) -> str | None:
    if profiled_path is None:
        return None
    if _same_file(path, profiled_path):
        return (
            f"{kind} skipped: path resolves to the profiled dataset; "
            "provide a separate evaluation file."
        )
    return None


def load_eval_bundle(
    dataset_config: dict,
    *,
    profiled_path: str | None = None,
) -> EvalBundle:
    """Load predictions / eval features / model from configured paths.

    If ``eval_path`` is missing, SHAP is skipped and the model is not loaded —
    even when ``model_path`` is set. Predictions are never generated by scoring
    any table; ``predictions_path`` must already contain ``y_pred``.
    """
    bundle = EvalBundle()

    predictions_path = configured_path(dataset_config.get("predictions_path"))
    eval_path = configured_path(dataset_config.get("eval_path"))
    model_path = configured_path(dataset_config.get("model_path"))

    if predictions_path is None:
        bundle.metrics_skip = (
            "Fairness metrics skipped: no predictions_path configured. "
            "Add a predictions CSV with y_true, y_pred, and protected attributes."
        )
    else:
        refused = _refuse_if_profiled(
            predictions_path, profiled_path, "Fairness metrics"
        )
        if refused:
            bundle.metrics_skip = refused
        elif not Path(predictions_path).is_file():
            bundle.metrics_skip = (
                "Fairness metrics skipped: predictions file not found: "
                f"{predictions_path}"
            )
        else:
            try:
                bundle.predictions = _read_csv(predictions_path, dataset_config)
            except (OSError, ValueError, UnicodeDecodeError) as exc:
                bundle.metrics_skip = (
                    f"Fairness metrics skipped: could not read predictions ({exc})."
                )

    if eval_path is None:
        bundle.shap_skip = (
            "SHAP skipped: eval_path is not configured "
            "(refusing to use the profiled dataset)."
        )
        return bundle

    refused = _refuse_if_profiled(eval_path, profiled_path, "SHAP")
    if refused:
        bundle.shap_skip = refused
        return bundle

    if not Path(eval_path).is_file():
        bundle.shap_skip = f"SHAP skipped: eval feature table not found: {eval_path}"
        return bundle

    try:
        bundle.eval_features = _read_csv(eval_path, dataset_config)
    except (OSError, ValueError, UnicodeDecodeError) as exc:
        bundle.shap_skip = f"SHAP skipped: could not read eval_path ({exc})."
        return bundle

    if model_path is None:
        bundle.shap_skip = (
            "SHAP skipped: model_path is not configured. "
            "Provide a joblib sklearn model together with eval_path."
        )
        return bundle

    if not Path(model_path).is_file():
        bundle.shap_skip = f"SHAP skipped: model file not found: {model_path}"
        return bundle

    try:
        bundle.model = joblib.load(model_path)
    except Exception as exc:
        bundle.shap_skip = f"SHAP skipped: could not load model ({exc})."
        return bundle

    return bundle
